#!/usr/bin/env python3
"""Build the recovered Qt UI separately; never overwrite the running binary."""
import os
from pathlib import Path
import re
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
BUILD = ROOT / '.native-build'
REV = '834a37e6b5b881e7af2866ca30f8202a8f376774'


def build():
  BUILD.mkdir(exist_ok=True)
  upstream = BUILD / 'upstream-ui.SConscript'
  if not upstream.exists():
    upstream.write_bytes(urllib.request.urlopen(
      f'https://raw.githubusercontent.com/MrXelious/FrogPilot/{REV}/selfdrive/ui/SConscript', timeout=30).read())
  sources = []
  for name in re.findall(r'"([^"\n]+\.cc)"', upstream.read_text().split('# build translation files')[0]):
    p = ROOT / name[1:] if name.startswith('#') else ROOT / 'selfdrive/ui' / name
    sources.append(p.resolve())
  sources += [p for p in (ROOT / 'common').glob('*.cc') if p.name != 'i2c.cc']
  sources += list((ROOT / 'common/transformations').glob('*.cc'))
  sources += [ROOT / 'third_party/json11/json11.cpp', ROOT / 'cereal/messaging/socketmaster.cc']
  sources += [ROOT / 'msgq_repo/msgq' / (name + '.cc') for name in
              ['ipc', 'msgq', 'event', 'impl_msgq', 'impl_zmq', 'impl_fake']]
  sources += [ROOT / 'msgq_repo/msgq/visionipc' / (name + '.cc') for name in
              ['visionipc', 'visionipc_client', 'visionipc_server', 'visionbuf', 'visionbuf_ion']]
  schemas = ['car', 'log', 'custom', 'legacy']
  if any(not (ROOT / f'cereal/gen/cpp/{s}.capnp.h').exists() or
         (ROOT / f'cereal/{s}.capnp').stat().st_mtime > (ROOT / f'cereal/gen/cpp/{s}.capnp.h').stat().st_mtime for s in schemas):
    subprocess.run(['capnpc', '--src-prefix=cereal', '-oc++:cereal/gen/cpp'] +
                   [f'cereal/{s}.capnp' for s in schemas], cwd=ROOT, check=True)
  sources += [ROOT / f'cereal/gen/cpp/{s}.capnp.c++' for s in schemas]
  sources += list((ROOT / 'selfdrive/ui/qt/offroad').glob('toadpilot*.cc'))
  services = subprocess.check_output(['python3', 'cereal/services.py'], cwd=ROOT)
  service_header = ROOT / 'cereal/services.h'
  if not service_header.exists() or service_header.read_bytes() != services:
    service_header.write_bytes(services)
  # QMapLibre's public include aliases are generated by its original build.
  aliases = ROOT / 'third_party/maplibre-native-qt/include/QMapLibre'
  aliases.mkdir(exist_ok=True)
  for name, header in {'Map': 'map.hpp', 'Settings': 'settings.hpp', 'Utils': 'utils.hpp',
                       'Types': 'types.hpp', 'Style': 'style.hpp', 'Export': 'export_core.hpp'}.items():
    path = aliases / name
    contents = f'#include "../{header}"\n'
    if not path.exists() or path.read_text() != contents:
      path.write_text(contents)
  headers = {p.with_suffix('.h') for p in sources if p.with_suffix('.h').exists()}
  headers.add(ROOT / 'selfdrive/ui/ui.h')
  # qmake otherwise gives both common/util.cc and qt/util.cc the same object name.
  common_util = BUILD / 'common_util.cc'
  original_util = (ROOT / 'common/util.cc').read_text()
  if not common_util.exists() or common_util.read_text() != original_util:
    common_util.write_text(original_util)
  sources = [common_util if p == ROOT / 'common/util.cc' else p for p in sources]
  yuv = ROOT / 'third_party/libyuv/larch64/lib/libyuv.a'
  if not yuv.exists():
    yuv.parent.mkdir(parents=True, exist_ok=True)
    yuv.write_bytes(urllib.request.urlopen(f'https://raw.githubusercontent.com/MrXelious/FrogPilot/{REV}/third_party/libyuv/larch64/lib/libyuv.a', timeout=30).read())
  project = [
    'QT += widgets gui-private network concurrent quick quickwidgets positioning dbus xml',
    'CONFIG += c++17 link_pkgconfig', 'CONFIG -= debug debug_and_release',
    'QMAKE_CXX = clang++', 'QMAKE_CC = clang',
    'QMAKE_CXXFLAGS_RELEASE = -O2 -g0 -Wno-deprecated-declarations',
    'QMAKE_LFLAGS += -no-pie',
    'DEFINES += QCOM2=1 ENABLE_MAPS', 'TARGET = ui-abrasax',
    'INCLUDEPATH += ' + ' '.join(str(ROOT / p) for p in
      ['', 'msgq_repo', 'msgq_repo/msgq', 'third_party/opencl/include', 'third_party/linux/include',
       'third_party/maplibre-native-qt/include', 'third_party/libyuv/include', 'third_party/qrcode',
       'selfdrive/frogpilot/screenrecorder/openmax/include']),
    'INCLUDEPATH += /usr/local/include /usr/include/eigen3',
    'LIBS += -L/usr/local/lib -L/system/vendor/lib64 -L/usr/lib/aarch64-linux-gnu '
    '-L' + str(ROOT / 'third_party/maplibre-native-qt/larch64/lib') +
    ' -lQMapLibre -lzmq -lcapnp -lkj -lOpenCL -lssl -lcrypto -lpthread -lavcodec -lavformat -lavutil -lOmxCore -lEGL -lwayland-client ' + str(yuv),
    'QMAKE_RPATHDIR += /usr/local/lib /data/openpilot/third_party/maplibre-native-qt/larch64/lib',
    'SOURCES += ' + ' '.join(str(p) for p in sorted(set(sources))),
    'HEADERS += ' + ' '.join(str(p) for p in sorted(headers)),
    'RESOURCES += ' + str(ROOT / 'selfdrive/assets/assets.qrc'),
  ]
  (BUILD / 'ui.pro').write_text('\n'.join(project) + '\n')
  subprocess.run(['qmake', 'ui.pro'], cwd=BUILD, check=True)
  # Qt's generated dispatch tables do not benefit from expensive optimization.
  # Keep the application optimized while making on-device rebuilds practical.
  with (BUILD / 'Makefile').open('a') as makefile:
    makefile.write('\nmoc_%.o: CXXFLAGS += -O0\n')
  subprocess.run(['nice', '-n', '10', 'make', '-j2'], cwd=BUILD, check=True)
  print(BUILD / 'ui-abrasax')


if __name__ == '__main__':
  build()
